export const getAllTags = () => {
  const tags = new Set();
  mockCakes.forEach(cake => {
    if (cake.custom) return;
    cake.tags.forEach(tag => {
      if (!tag.toLowerCase().includes('birthday') && !tag.toLowerCase().includes('anniversary')) {
        tags.add(tag);
      }
    });
  });
  return Array.from(tags).sort();
};

